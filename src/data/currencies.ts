import { Currency, HistoricalPoint } from '../types/currency';

function generateHistory(currentRate: number, volatility: number = 0.008): Currency['historicalData'] {
  const now = new Date();

  const createPoints = (days: number): HistoricalPoint[] => {
    const points: HistoricalPoint[] = [];
    let rate = currentRate * (1 + (Math.sin(days) * 0.015 - 0.008));
    
    for (let i = days; i >= 0; i--) {
      const d = new Date(now);
      d.setDate(d.getDate() - i);
      const dateStr = d.toISOString().split('T')[0];
      
      // Gentle pseudo-realistic random walk ending on currentRate
      const progress = 1 - (i / days);
      const noise = (Math.sin(i * 1.3) * 0.5 + Math.cos(i * 0.7) * 0.5) * volatility * currentRate;
      const targetWeight = progress * progress;
      const pointRate = (rate + noise) * (1 - targetWeight) + currentRate * targetWeight;
      
      points.push({
        date: dateStr,
        rate: Number(pointRate.toFixed(pointRate > 100 ? 2 : pointRate > 10 ? 3 : 4)),
      });
      rate = pointRate;
    }
    // Make sure the last point matches currentRate exactly
    if (points.length > 0) {
      points[points.length - 1].rate = currentRate;
    }
    return points;
  };

  return {
    '7D': createPoints(7),
    '30D': createPoints(30),
    '90D': createPoints(90),
    '1Y': createPoints(365),
  };
}

